// Run using Electron's Node runtime (better-sqlite3 uses Electron's ABI).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const Database = require('better-sqlite3');
const root = path.resolve(__dirname, '..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'portal-mbend-test-'));
const db = new Database(':memory:');
db.pragma('foreign_keys = ON');
const modules = new Map();
function load(relative, stubs = {}) {
  if (modules.has(relative)) return modules.get(relative);
  const source = fs.readFileSync(path.join(root, relative), 'utf8');
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText;
  const module = { exports: {} };
  vm.runInThisContext(`(function(require,module,exports){${code}\n})`, { filename: relative })((name) => name in stubs ? stubs[name] : require(name), module, module.exports);
  modules.set(relative, module.exports);
  return module.exports;
}
async function main() {
  const shared = load('src/shared/mBendGeometry.ts');
  const schema = load('src/main/db/mBendSchema.ts');
  db.exec("CREATE TABLE schema_meta (id INTEGER PRIMARY KEY, version INTEGER, updatedAt TEXT); INSERT INTO schema_meta VALUES (1,1,'old')");
  schema.initMBendSchema(db);
  assert.equal(db.prepare('SELECT version FROM schema_meta').get().version, 2);
  db.exec("INSERT INTO m_upper_tools(id,code,name) VALUES (1,'P1','Punch'); INSERT INTO m_lower_tools(id,code,name) VALUES (1,'D1','Die')");
  schema.initMBendSchema(db);
  assert.equal(db.prepare('SELECT count(*) n FROM m_upper_tools').get().n, 1);
  const connection = { getMBendDb: () => db, getMBendDbPath: () => path.join(temp, 'm-bend.db') };
  const repo = load('src/main/modules/m-bend/m-bend-geometry.repo.ts', { '@shared/mBendGeometry.js': shared, '@main/db/mBendConnection.js': connection });
  const service = load('src/main/modules/m-bend/m-bend-geometry.service.ts', { '@shared/mBendGeometry.js': shared, '@main/db/mBendConnection.js': connection, './m-bend-geometry.repo.js': repo });
  const target = { table: 'm_upper_tools', id: 1 };
  const lower = { table: 'm_lower_tools', id: 1 };
  const placement = { ...shared.defaultPlacement(), anchor: [10,20,30], rotationDeg: [0,0,90], offset: [4,5,6] };
  const matrix = shared.placementMatrix(placement);
  const transform = (p) => [0,1,2].map((i) => matrix[i]*p[0] + matrix[4+i]*p[1] + matrix[8+i]*p[2] + matrix[12+i]);
  transform(placement.anchor).forEach((v,i) => assert.ok(Math.abs(v - placement.offset[i]) < 1e-8));
  const moved = transform([11,20,30]);
  moved.forEach((v,i) => assert.ok(Math.abs(v - [4,6,6][i]) < 1e-8));
  assert.throws(() => shared.validateGeometryTarget({ table: 'm_machines', id: 1 }));
  assert.throws(() => shared.validateGeometryTarget({ table: 'm_upper_tools', id: -1 }));
  assert.throws(() => shared.validatePlacement({ ...placement, mountNormal: [0,0,0] }));
  assert.throws(() => shared.validatePlacement({ ...placement, offset: [NaN,0,0] }));
  assert.equal(service.getGeometry(target).revision, 0);
  const saved = service.savePlacement({ ...target, revision: 0, placement });
  assert.equal(saved.revision, 1);
  assert.equal(service.getGeometry(lower).revision, 0);
  assert.throws(() => service.savePlacement({ ...target, revision: 0, placement }));
  const source = path.join(temp, 'sample.step');
  fs.writeFileSync(source, 'ISO-10303-21;\nHEADER;ENDSEC;DATA;ENDSEC;END-ISO-10303-21;');
  const imported = await service.importStep(target, 1, source);
  assert.equal(imported.revision, 2);
  assert.deepEqual(imported.placement, shared.defaultPlacement());
  const adjusted = service.savePlacement({ ...target, revision: 2, placement });
  const same = await service.importStep(target, adjusted.revision, source);
  assert.deepEqual(same.placement, placement);
  assert.ok((await service.readModel(target)).base64.length > 0);
  const exported = service.exportGeometry(target);
  assert.equal(exported.unit, 'mm');
  assert.equal(exported.sourceToToolMatrix.length, 16);
  assert.ok(fs.existsSync(exported.stepPath));
  assert.equal(service.exportGeometry(lower), null);
  const oldFile = exported.stepPath;
  fs.appendFileSync(source, '\n/*changed*/');
  const replacement = await service.importStep(target, same.revision, source);
  assert.notEqual(replacement.sha256, same.sha256);
  assert.ok(fs.existsSync(oldFile), 'replacement must preserve previous STEP');
  assert.deepEqual(replacement.placement, shared.defaultPlacement());
  fs.writeFileSync(source, 'not STEP');
  await assert.rejects(service.importStep(target, replacement.revision, source));
  assert.equal(service.getGeometry(target).revision, replacement.revision);
  db.prepare('DELETE FROM m_upper_tools WHERE id=1').run();
  assert.equal(db.prepare('SELECT count(*) n FROM tool_geometry').get().n, 0);
  db.prepare('UPDATE schema_meta SET version=3').run();
  assert.throws(() => schema.initMBendSchema(db));
  assert.equal(db.prepare('SELECT version FROM schema_meta').get().version, 3);
  console.log('PASS: migration, isolation, validation, coordinates, conflict, STEP import/read/export/replacement, FK cascade, forward-version guard');
}
main().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => {
  db.close();
  if (path.dirname(temp) === path.resolve(os.tmpdir()) && path.basename(temp).startsWith('portal-mbend-test-')) fs.rmSync(temp, { recursive: true, force: true });
});
